// =========================================================
// Capability Types
//
// Each capability is a self-contained type that holds both
// the underlying implementation and any permission
// configuration. Permission checking happens inside the
// capability — callers never need to pre-check.
//
// The `ProvisionedCaps` struct bundles all capabilities for
// a single gadget instance. Each field is `Option<Arc<...>>`
// — present if the gadget requested the capability, absent
// if it didn't. The `cap_accessor!` macro generates typed
// accessor methods that panic with a clear message if the
// capability wasn't provisioned.
// =========================================================

